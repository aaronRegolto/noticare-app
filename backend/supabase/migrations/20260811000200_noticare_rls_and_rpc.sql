-- Validate the exact indicator-code allow-list for a published rule version.
-- This prevents clients from using an analytics field as a covert channel for
-- raw messages or URLs, while allowing old queued events to use old rule sets.
create or replace function public.assert_indicator_codes(
  p_codes text[],
  p_rule_version text
)
returns void
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_rule_bundle jsonb;
begin
  if char_length(trim(coalesce(p_rule_version, ''))) not between 1 and 64 then
    raise exception 'invalid rule version' using errcode = '22023';
  end if;

  if cardinality(coalesce(p_codes, '{}'::text[])) > 32 then
    raise exception 'too many indicator codes' using errcode = '22023';
  end if;

  select r.rule_bundle
  into v_rule_bundle
  from public.rule_sets as r
  where r.version = trim(p_rule_version);

  if not found or jsonb_typeof(v_rule_bundle -> 'allowedIndicatorCodes') <> 'array' then
    raise exception 'unknown or invalid rule version' using errcode = '22023';
  end if;

  if exists (
    select 1
    from unnest(coalesce(p_codes, '{}'::text[])) as code(value)
    where char_length(code.value) > 64
      or code.value !~ '^[a-z0-9][a-z0-9_.:-]{0,63}$'
      or not ((v_rule_bundle -> 'allowedIndicatorCodes') ? code.value)
  ) then
    raise exception 'indicator codes must be in the published rule-set allow-list'
      using errcode = '22023';
  end if;
end;
$$;

revoke all on function public.assert_indicator_codes(text[], text) from public, anon, authenticated;

-- Registers an anonymous installation UUID for the signed-in user. The UUID is
-- generated by the app and is not based on a hardware or advertising ID.
create or replace function public.register_device(
  p_installation_id uuid,
  p_app_version text,
  p_rule_version text
)
returns public.devices
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_user_id uuid := auth.uid();
  v_device public.devices;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;

  if p_installation_id is null
    or char_length(trim(coalesce(p_app_version, ''))) not between 1 and 64
    or char_length(trim(coalesce(p_rule_version, ''))) not between 1 and 64 then
    raise exception 'invalid device metadata' using errcode = '22023';
  end if;

  insert into public.devices (
    user_id,
    installation_id,
    app_version,
    rule_version,
    last_seen_at
  )
  values (
    v_user_id,
    p_installation_id,
    trim(p_app_version),
    trim(p_rule_version),
    now()
  )
  on conflict (user_id, installation_id) do update
    set app_version = excluded.app_version,
        rule_version = excluded.rule_version,
        last_seen_at = now(),
        updated_at = now()
  returning * into v_device;

  return v_device;
end;
$$;

-- Stores privacy-safe event metadata and updates the aggregate trigger exactly
-- once. A duplicate client_event_id returns the original ID only for its owner.
create or replace function public.record_threat_event(
  p_client_event_id uuid,
  p_device_id uuid,
  p_source public.threat_source,
  p_threat_level public.threat_level,
  p_score_bucket smallint,
  p_blocked boolean,
  p_indicator_codes text[],
  p_url_count smallint,
  p_rule_version text,
  p_occurred_at timestamptz,
  p_is_demo boolean default false
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_user_id uuid := auth.uid();
  v_event_id uuid;
  v_existing_user_id uuid;
  v_existing_device_id uuid;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;

  if p_client_event_id is null
    or p_device_id is null
    or p_score_bucket not between 0 and 10
    or p_url_count not between 0 and 20
    or char_length(trim(coalesce(p_rule_version, ''))) not between 1 and 64
    or p_occurred_at is null
    or p_occurred_at < now() - interval '90 days'
    or p_occurred_at > now() + interval '5 minutes' then
    raise exception 'invalid threat event metadata' using errcode = '22023';
  end if;

  if p_blocked and (
    p_source <> 'realtime'::public.threat_source
    or p_threat_level <> 'dangerous'::public.threat_level
  ) then
    raise exception 'only realtime dangerous events may be blocked'
      using errcode = '22023';
  end if;

  perform public.assert_indicator_codes(p_indicator_codes, trim(p_rule_version));

  if not exists (
    select 1
    from public.devices as d
    where d.id = p_device_id
      and d.user_id = v_user_id
  ) then
    raise exception 'device is not registered to the current user'
      using errcode = '42501';
  end if;

  select e.id, e.user_id, e.device_id
  into v_event_id, v_existing_user_id, v_existing_device_id
  from public.threat_events as e
  where e.client_event_id = p_client_event_id;

  if found then
    if v_existing_user_id = v_user_id and v_existing_device_id = p_device_id then
      return v_event_id;
    end if;

    raise exception 'client event ID is already owned by another account'
      using errcode = '42501';
  end if;

  begin
    insert into public.threat_events (
      client_event_id,
      user_id,
      device_id,
      source,
      threat_level,
      score_bucket,
      blocked,
      indicator_codes,
      url_count,
      rule_version,
      occurred_at,
      is_demo
    )
    values (
      p_client_event_id,
      v_user_id,
      p_device_id,
      p_source,
      p_threat_level,
      p_score_bucket,
      p_blocked,
      coalesce(p_indicator_codes, '{}'::text[]),
      p_url_count,
      trim(p_rule_version),
      p_occurred_at,
      coalesce(p_is_demo, false)
    )
    returning id into v_event_id;
  exception
    when unique_violation then
      -- A concurrent retry may win the unique-index race. Return its ID only if
      -- it belongs to this exact user/device pair.
      select e.id, e.user_id, e.device_id
      into v_event_id, v_existing_user_id, v_existing_device_id
      from public.threat_events as e
      where e.client_event_id = p_client_event_id;

      if v_existing_user_id = v_user_id and v_existing_device_id = p_device_id then
        return v_event_id;
      end if;

      raise exception 'client event ID is already owned by another account'
        using errcode = '42501';
  end;

  return v_event_id;
end;
$$;

-- Records a user correction without accepting a message, sender, URL, or
-- clipboard value. If it references an event, ownership is checked.
create or replace function public.submit_scan_feedback(
  p_event_id uuid,
  p_expected_level public.threat_level,
  p_indicator_codes text[],
  p_rule_version text
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_user_id uuid := auth.uid();
  v_feedback_id uuid;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;

  if char_length(trim(coalesce(p_rule_version, ''))) not between 1 and 64 then
    raise exception 'invalid rule version' using errcode = '22023';
  end if;

  perform public.assert_indicator_codes(p_indicator_codes, trim(p_rule_version));

  if p_event_id is not null and not exists (
    select 1
    from public.threat_events as e
    where e.id = p_event_id
      and e.user_id = v_user_id
  ) then
    raise exception 'event is not owned by the current user'
      using errcode = '42501';
  end if;

  insert into public.scan_feedback (
    user_id,
    event_id,
    expected_level,
    indicator_codes,
    rule_version
  )
  values (
    v_user_id,
    p_event_id,
    p_expected_level,
    coalesce(p_indicator_codes, '{}'::text[]),
    trim(p_rule_version)
  )
  returning id into v_feedback_id;

  return v_feedback_id;
end;
$$;

-- Gives the mobile dashboard aggregate-only counts. Bucket boundaries are UTC;
-- the client formats them in the user's locale. Empty time buckets are filled by
-- the client so this RPC never needs to fabricate zero rows.
create or replace function public.get_community_stats(p_range text)
returns table (
  date timestamptz,
  safe_count bigint,
  suspicious_count bigint,
  dangerous_count bigint,
  blocked_count bigint
)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_day_start timestamptz := date_trunc('day', now() at time zone 'UTC') at time zone 'UTC';
  v_start_date date;
  v_start_month date;
begin
  if p_range not in ('today', 'last_7_days', 'last_30_days', 'last_6_months') then
    raise exception 'unsupported community range' using errcode = '22023';
  end if;

  if p_range = 'today' then
    return query
    select
      h.bucket_start as date,
      h.safe_count,
      h.suspicious_count,
      h.dangerous_count,
      h.successfully_blocked_count as blocked_count
    from public.community_hourly_stats as h
    where h.bucket_start >= v_day_start
      and h.bucket_start < v_day_start + interval '1 day'
    order by h.bucket_start;
    return;
  end if;

  if p_range = 'last_7_days' then
    v_start_date := (v_day_start at time zone 'UTC')::date - 6;
  elsif p_range = 'last_30_days' then
    v_start_date := (v_day_start at time zone 'UTC')::date - 29;
  else
    v_start_month := (date_trunc('month', v_day_start at time zone 'UTC') - interval '5 months')::date;
  end if;

  if p_range in ('last_7_days', 'last_30_days') then
    return query
    select
      d.bucket_date::timestamp at time zone 'UTC' as date,
      d.safe_count,
      d.suspicious_count,
      d.dangerous_count,
      d.successfully_blocked_count as blocked_count
    from public.community_daily_stats as d
    where d.bucket_date >= v_start_date
      and d.bucket_date <= (v_day_start at time zone 'UTC')::date
    order by d.bucket_date;
    return;
  end if;

  return query
  select
    date_trunc('month', d.bucket_date::timestamp) at time zone 'UTC' as date,
    coalesce(sum(d.safe_count), 0)::bigint as safe_count,
    coalesce(sum(d.suspicious_count), 0)::bigint as suspicious_count,
    coalesce(sum(d.dangerous_count), 0)::bigint as dangerous_count,
    coalesce(sum(d.successfully_blocked_count), 0)::bigint as blocked_count
  from public.community_daily_stats as d
  where d.bucket_date >= v_start_month
    and d.bucket_date <= (v_day_start at time zone 'UTC')::date
  group by date_trunc('month', d.bucket_date::timestamp)
  order by date_trunc('month', d.bucket_date::timestamp);
end;
$$;

